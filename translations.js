function applyTranslations() {
  const lang = document.documentElement.lang || "en";
  const dict =
    portfolioTranslations[lang] || portfolioTranslations.en;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");

    if (dict[key] !== undefined) {
      if (el.tagName === "INPUT" && el.placeholder !== undefined) {
        el.placeholder = dict[key];
      } else {
        el.innerHTML = dict[key];
      }
    }
  });
}

function setPortfolioLanguage(lang) {
  if (!portfolioTranslations[lang]) {
    lang = "en";
  }

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  localStorage.setItem("badye-lang", lang);

  const selects = document.querySelectorAll(
    "#langSelect,#langSelectMobile"
  );

  selects.forEach((s) => {
    s.value = lang;
  });

  applyTranslations();
}

window.applyTranslations = applyTranslations;
window.setPortfolioLanguage = setPortfolioLanguage;

document.addEventListener("DOMContentLoaded", () => {
  const saved = localStorage.getItem("badye-lang") || "en";
  setPortfolioLanguage(saved);
});